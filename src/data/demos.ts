export type DemoTone =
  | "default"
  | "dim"
  | "accent"
  | "ok"
  | "warn"
  | "err"
  | "info"
  | "bold"
  | "mint"
  | "amber"
  | "sky";

export type DemoSegment = { text: string; tone?: DemoTone };
export type DemoLine = DemoSegment[];

export type Demo = {
  id: string;
  tool: string;
  label: string;
  command: string;
  exit: number;
  time: string;
  lang: "fr" | "en";
  note?: string;
  lines: DemoLine[];
};

const s = (text: string, tone: DemoTone = "default"): DemoSegment => ({ text, tone });
const l = (...segments: DemoSegment[]): DemoLine => segments;

